CREATE TABLE IF NOT EXISTS jp_users (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    email VARCHAR(254) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    session_version INT UNSIGNED NOT NULL DEFAULT 1,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS jp_records (
    user_id BIGINT UNSIGNED NOT NULL,
    collection VARCHAR(20) NOT NULL,
    record_id VARCHAR(80) NOT NULL,
    payload LONGTEXT NOT NULL,
    PRIMARY KEY (user_id, collection, record_id),
    CONSTRAINT jp_records_user FOREIGN KEY (user_id) REFERENCES jp_users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS jp_login_limits (
    attempt_key CHAR(64) NOT NULL PRIMARY KEY,
    attempts INT UNSIGNED NOT NULL DEFAULT 1,
    expires_at BIGINT NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
